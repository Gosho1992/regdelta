"""Renders agents/*.md and the Switch templates from one source of truth.

Run after editing agent briefs: python scripts/build_templates.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGENTS = [
    ("spec-analyst", "Specification Analyst", "Compares the previous and revised reporting specs and posts the Change Register", "specification-analyst.md"),
    ("asset-mapper", "Asset Mapper", "Traces each change through SQL, ETL, reports, dashboards and exports with file:line evidence", "asset-mapper.md"),
    ("remediation-planner", "Remediation Planner", "Writes the prioritised remediation plan once the human owner has approved", "remediation-planner.md"),
]


def brief(name, prefix, owner):
    t = (ROOT / "agents" / name).read_text(encoding="utf-8")
    return (t.replace("@ASSET_MAPPER", f"@{prefix}-asset-mapper").replace("@PLANNER", f"@{prefix}-remediation-planner")
             .replace("PLANNER", f"{prefix}-remediation-planner").replace("OWNER", owner))


def indent(text, n):
    pad = " " * n
    return "\n".join(pad + l if l.strip() else "" for l in text.splitlines())


def agents_block(prefix, owner):
    out = []
    for key, disp, desc, md in AGENTS:
        out.append(f"""  - name: "{prefix}-{key}"
    display_name: "{disp}"
    description: "{desc}"
    addressing: owner-agents
    provider: "{{provider}}"
    location: "{{location}}"
    directory: "{{workspace}}"
    instructions: |
{indent(brief(md, prefix, owner), 6)}""")
    return "\n".join(out)


PARAMS = """params:
  prefix:
    type: string
    label: Name prefix
    description: Prefix for the three agent names (must be unique on your server)
    default: regdelta
    pattern: "[a-z][a-z0-9-]*"
  provider:
    type: provider
    description: Coding agent behind all three. The first one installed is chosen.
    default: [claude, codex, opencode]
    input: advanced
  location:
    type: location
    default: local
    input: advanced
  workspace:
    type: directory
    label: Shared working directory
    description: One folder shared by all three agents, so they see the same RegDelta outputs.
    default: "{$agents_dir}/regdelta-room"
    input: advanced
"""

HEADER = """# RegDelta Impact Room - generated by scripts/build_templates.py; edit agents/*.md instead.
#
# Three agents share one working directory (the RegDelta repo is cloned there
# on first use) and hand work to each other in one room. The Human Reporting
# Owner approves in the same room; RegDelta's gate blocks the plan until then.
version: 1

"""


def main():
    owner_room = "{$creator}"
    room_instr = (ROOT / "switch" / "room-instructions.md").read_text(encoding="utf-8")
    # 1) full template: creates agents + room (Discord, Slack, Mattermost, Teams)
    full = HEADER + PARAMS + """  bridge:
    type: bridge
    description: Messaging app for the room. Telegram cannot create chats - use regdelta-team.template.yaml there.
    default: [Discord, Slack, Mattermost, $first]
  change_name:
    type: string
    label: Change package
    default: "PRF 3.1 to 3.2"

agents:
""" + agents_block("{prefix}", owner_room) + f"""

room:
  name: "regdelta-impact-room"
  description: "Impact assessment for {{change_name}}: three agents trace it, you approve, then the plan is written."
  bridge: "{{bridge}}"
  agents: ["{{prefix}}-spec-analyst", "{{prefix}}-asset-mapper", "{{prefix}}-remediation-planner"]
  users: ["{{$creator}}"]
  instructions: |
{indent(room_instr, 4)}
  roles:
    - name: reporting-owner-review
      exclusive: true
      instructions: Only the Human Reporting Owner approves findings. Agents never take this role.
  docs:
    - name: How to review
      description: The reply format the Remediation Planner understands
      instructions: Show this to the Human Reporting Owner when asking for a review.
      content: |
        Reply to the Remediation Planner in one message, for example:
        @{{prefix}}-remediation-planner confirm all evidenced, investigate F-006, F-031, reject F-033
        Words it understands: all-evidenced, candidates, all, CHG-05, F-012.
        Anything you don't mention stays "needs investigation".

kickoff: |
  @{{prefix}}-spec-analyst New reporting change package: {{change_name}} (Harbourview Bank, fictional demo data in fixtures/harbourview-bank). Build the Change Register and hand it to the Asset Mapper. I am the Human Reporting Owner and will review before any plan is made.
"""
    (ROOT / "switch" / "regdelta-room.template.yaml").write_text(full, encoding="utf-8")

    # 2) team template: agents join a room that already exists (Telegram groups)
    team = HEADER + PARAMS + """  room:
    type: room
    label: Room to join
    description: An existing room, e.g. the Telegram group you added the Switch bot to.

agents:
""" + agents_block("{prefix}", owner_room).replace('    instructions: |', '    join: ["{room}"]\n    instructions: |') + "\n"
    (ROOT / "switch" / "regdelta-team.template.yaml").write_text(team, encoding="utf-8")

    # 3) rendered briefs for people reading the repo
    for key, disp, desc, md in AGENTS:
        (ROOT / "agents" / "rendered").mkdir(exist_ok=True)
        (ROOT / "agents" / "rendered" / md).write_text(brief(md, "regdelta", "the Human Reporting Owner"), encoding="utf-8")
    print("templates written")


if __name__ == "__main__":
    main()
